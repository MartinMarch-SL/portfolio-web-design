import { readFile } from 'node:fs/promises'
import { expect, test } from '@playwright/test'

const base = '/portfolio-web-design/las-moreras/'

test('preinscripción con validación, restauración y justificante', async ({ page }) => {
  await page.goto(base)
  await page.getByLabel('Año de nacimiento', { exact: true }).selectOption('2016')
  await expect(page.locator('[data-school-category]')).toHaveText('Alevín')
  await page.getByRole('button', { name: 'Empezar preinscripción' }).click()
  const next = page.getByRole('button', { name: 'Continuar' })
  await expect(page.getByLabel('Año', { exact: true })).toHaveValue('2016')
  await next.click()
  await expect(page.getByText('Indica una fecha de nacimiento válida.')).toBeVisible()
  await page.getByRole('combobox', { name: 'Día', exact: true }).selectOption('29')
  await page.getByRole('combobox', { name: 'Mes', exact: true }).selectOption('02')
  await page.getByLabel('Nivel', { exact: true }).selectOption('Competición')
  await expect(page.locator('[data-trial]')).toBeVisible()
  await page.getByLabel('Días por semana').selectOption('2')
  await page.getByLabel('Forma de pago').selectOption('quarterly')
  await next.click()
  await page.getByLabel('Nombre', { exact: true }).fill('Ada <Ruiz>')
  await page.getByLabel('Apellidos', { exact: true }).fill('García')
  await page.getByLabel('Mano dominante').selectOption('Zurda')
  await page.getByLabel('Experiencia previa').selectOption('Un año o más')
  await page.getByLabel('Talla del polo').selectOption('12')
  await page.getByLabel(/segundo hermano inscrito/).check()
  await page.reload()
  await expect(page.getByLabel('Nombre', { exact: true })).toHaveValue('Ada <Ruiz>')
  await expect(page.getByLabel(/segundo hermano inscrito/)).toBeChecked()
  await next.click()
  const review = page.getByRole('button', { name: 'Ver resumen' })
  await page.getByLabel('Nombre y apellidos del tutor o tutora').fill('Luis García')
  await page.getByLabel('DNI o NIE del tutor').fill('12345678A')
  await review.click()
  await expect(page.getByText('Comprueba el número y la letra del DNI o NIE.')).toBeVisible()
  await expect(page.getByText('Introduce un teléfono español válido.')).toBeVisible()
  await page.getByLabel('DNI o NIE del tutor').fill('12345678Z')
  await page.getByLabel('Teléfono').fill('+34 612 345 678')
  await page.getByLabel('Correo electrónico').fill('luis@example.com')
  await page.getByLabel(/Número de socio/).fill('12345')
  await page.getByLabel(/Autorizo la atención médica/).check()
  await page.getByLabel('Autorización de imagen').selectOption('No autorizo')
  await page.getByLabel(/He leído que los datos/).check()
  await review.click()
  await expect(page.locator('[data-code]')).toHaveText(/^CTM-26-[A-Z0-9]{5}$/)
  const code = await page.locator('[data-code]').textContent()
  await expect(page.locator('[data-ficha-total]')).toContainText('215,32')
  await page.reload()
  await expect(page.locator('[data-code]')).toHaveText(code!)
  const [download] = await Promise.all([
    page.waitForEvent('download'), page.getByRole('button', { name: 'Descargar justificante' }).click(),
  ])
  expect(download.suggestedFilename()).toBe(code + '.html')
  const receipt = await readFile((await download.path())!, 'utf8')
  expect(receipt).toContain('Ada &lt;Ruiz&gt; García')
  expect(receipt).toContain('Pendiente de prueba de nivel')
  expect(receipt).toContain('215,32')
  expect(receipt).toContain('Demostración: no se envía ningún dato')
  await page.getByRole('button', { name: 'Empezar de nuevo' }).click()
  await page.reload()
  await expect(page.getByLabel('Año', { exact: true })).toHaveValue('')
})

test('reserva móvil con luz, calendario, restauración y cancelación', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await page.clock.setFixedTime(new Date(2026, 10, 23, 10))
  await page.goto(base + 'reservas/')
  await page.locator('[data-day]').nth(1).click()
  await page.getByLabel('Superficie').selectOption('clay')
  const occupied = page.locator('[data-slot]:disabled').first()
  await expect(occupied).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Confirmar reserva' })).toBeDisabled()
  const free = page.locator('[data-slot$="/19"]:enabled').first()
  const slot = await free.getAttribute('data-slot')
  await free.click()
  const selected = page.locator(`[data-slot="${slot}"]`)
  await expect(selected).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('[data-booking-total]')).toContainText('16,00')
  await page.getByLabel('Soy socio o socia').check()
  await page.getByLabel('Número de jugadores').selectOption('4')
  await expect(page.locator('[data-booking-total]')).toContainText('10,00')
  await page.reload()
  await expect(selected).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByLabel('Número de jugadores')).toHaveValue('4')
  await page.getByRole('button', { name: 'Confirmar reserva' }).click()
  const ticket = page.locator('[data-active] article')
  await expect(ticket.locator('h3')).toHaveText(/^CTM-R-[A-Z0-9]{5}$/)
  await expect(ticket).toContainText(/4 jugadores.*10,00/)
  const code = await ticket.locator('h3').textContent()
  const [download] = await Promise.all([
    page.waitForEvent('download'), ticket.getByRole('button', { name: 'Descargar .ics' }).click(),
  ])
  expect(download.suggestedFilename()).toBe(code + '.ics')
  const calendar = await readFile((await download.path())!, 'utf8')
  expect(calendar).toContain('BEGIN:VEVENT')
  expect(calendar).toMatch(/DTSTART:\d{8}T190000\r\nDTEND:\d{8}T200000/)
  await page.reload()
  await expect(ticket.locator('h3')).toHaveText(code!)
  await expect(selected).toBeDisabled()
  await ticket.getByRole('button', { name: 'Cancelar reserva' }).click()
  await expect(selected).toBeEnabled()
  await page.reload()
  await expect(page.locator('[data-active]')).toHaveText('No tienes reservas activas.')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(375)
})
